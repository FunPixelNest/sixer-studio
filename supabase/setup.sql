-- ---------- Admins (who can manage products, orders and settings) ----------
create table if not exists public.admins (
  email text primary key
);
alter table public.admins enable row level security;   -- no policies = nobody can read/edit it from the website

create or replace function public.is_admin()
returns boolean
language sql stable security definer
set search_path = public
as $$
  select exists (
    select 1 from public.admins
    where lower(email) = lower(coalesce(auth.jwt() ->> 'email', ''))
  );
$$;
grant execute on function public.is_admin() to anon, authenticated;

-- ---------- Products ----------
create table if not exists public.products (
  id           uuid primary key default gen_random_uuid(),
  name         text not null,
  category     text not null default 'polo',
  price        numeric not null default 0,
  mrp          numeric,
  description  text not null default '',
  images       text[] not null default '{}',
  sizes        text[] not null default '{S,M,L,XL,2XL}',
  customizable boolean not null default true,
  tag          text not null default '',
  active       boolean not null default true,
  sort         int not null default 0,
  created_at   timestamptz not null default now()
);
alter table public.products enable row level security;

drop policy if exists "products: anyone can view visible products" on public.products;
create policy "products: anyone can view visible products" on public.products
  for select using (active or public.is_admin());
drop policy if exists "products: admin insert" on public.products;
create policy "products: admin insert" on public.products
  for insert with check (public.is_admin());
drop policy if exists "products: admin update" on public.products;
create policy "products: admin update" on public.products
  for update using (public.is_admin()) with check (public.is_admin());
drop policy if exists "products: admin delete" on public.products;
create policy "products: admin delete" on public.products
  for delete using (public.is_admin());

-- ---------- Orders (bookings) ----------
create table if not exists public.orders (
  id             bigint generated by default as identity (start with 1001) primary key,
  user_id        uuid default auth.uid() references auth.users (id) on delete set null,
  email          text,
  customer_name  text not null,
  phone          text not null,
  address        text not null,
  city           text not null default '',
  pincode        text not null default '',
  note           text not null default '',
  items          jsonb not null default '[]',
  total          numeric not null default 0,
  status         text not null default 'new'
                 check (status in ('new','confirmed','printing','shipped','delivered','cancelled')),
  delivery_date  date,
  admin_note     text not null default '',
  created_at     timestamptz not null default now()
);
alter table public.orders enable row level security;

drop policy if exists "orders: customers create their own" on public.orders;
create policy "orders: customers create their own" on public.orders
  for insert to authenticated
  with check (user_id = auth.uid() and status = 'new' and delivery_date is null);
drop policy if exists "orders: customers see their own, admin sees all" on public.orders;
create policy "orders: customers see their own, admin sees all" on public.orders
  for select using (user_id = auth.uid() or public.is_admin());
drop policy if exists "orders: admin update" on public.orders;
create policy "orders: admin update" on public.orders
  for update using (public.is_admin()) with check (public.is_admin());
drop policy if exists "orders: admin delete" on public.orders;
create policy "orders: admin delete" on public.orders
  for delete using (public.is_admin());

-- ---------- Store settings (WhatsApp number, store name, prices…) ----------
create table if not exists public.settings (
  id    int primary key default 1 check (id = 1),
  data  jsonb not null default '{}'
);
alter table public.settings enable row level security;

drop policy if exists "settings: anyone can read" on public.settings;
create policy "settings: anyone can read" on public.settings
  for select using (true);
drop policy if exists "settings: admin insert" on public.settings;
create policy "settings: admin insert" on public.settings
  for insert with check (public.is_admin());
drop policy if exists "settings: admin update" on public.settings;
create policy "settings: admin update" on public.settings
  for update using (public.is_admin()) with check (public.is_admin());

insert into public.settings (id, data) values (1, '{}') on conflict (id) do nothing;

-- ---------- Table permissions (row-level security above still decides which rows) ----------
grant select on public.products, public.settings to anon, authenticated;
grant insert, update, delete on public.products, public.settings to authenticated;
grant select, insert, update, delete on public.orders to authenticated;
grant usage, select on all sequences in schema public to authenticated;

